import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';

await build({
  entryPoints: ['ui/fluent.js'],
  outfile: 'public/fluent-ui.js',
  bundle: true,
  format: 'esm',
  target: ['es2022'],
  minify: true,
  legalComments: 'eof',
  banner: { js: '/* Generated by npm run build:ui. Source: ui/fluent.js. Fluent UI 3.2.1. Licenses: /fluent-ui.LICENSE.txt */' },
  logLevel: 'info',
});

const notices = await Promise.all([
  readFile('ui/MICROSOFT-LICENSE.txt', 'utf8'),
  readFile('node_modules/tslib/CopyrightNotice.txt', 'utf8'),
  readFile('node_modules/tslib/LICENSE.txt', 'utf8'),
]);
await writeFile('public/fluent-ui.LICENSE.txt', notices.join('\n\n'));
